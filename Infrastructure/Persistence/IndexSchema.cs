using Npgsql;

namespace Indexer.Infrastructure.Persistence;

/// <summary>The index tables SearchAPI reads. Shared by the batch store and the pipeline writer.</summary>
public static class IndexSchema
{
    /// <summary>
    /// Drops and recreates <c>document</c>, <c>word</c> and <c>occ</c>. The ids are identity columns
    /// that accept explicit values, so the batch store can assign its own ids and the pipeline writers
    /// let the database assign them. <c>url</c> is unique so that writing a document twice is detectable.
    /// </summary>
    public static void Recreate(NpgsqlConnection connection)
    {
        Execute(connection, "DROP TABLE IF EXISTS occ");
        Execute(connection, "DROP TABLE IF EXISTS document");
        Execute(connection, "DROP TABLE IF EXISTS word");

        Execute(connection, "CREATE TABLE document(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, url TEXT UNIQUE, idxTime TEXT, creationTime TEXT)");
        Execute(connection, "CREATE TABLE word(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE)");
        Execute(connection, "CREATE TABLE occ(wordId INTEGER REFERENCES word(id), docId INTEGER REFERENCES document(id))");
        Execute(connection, "CREATE INDEX word_index ON occ (wordId)");
        Execute(connection, "CREATE INDEX occ_doc ON occ (docId, wordId)");
    }

    private static void Execute(NpgsqlConnection connection, string sql)
    {
        using var cmd = new NpgsqlCommand(sql, connection);
        cmd.ExecuteNonQuery();
    }
}
